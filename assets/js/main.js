/* =========================================================
   Git Zero to Pro: shared site behavior
   OWNER: main model. Contributors: do NOT edit this file.

   What it does:
   - renders the header, sidebar, footer and prev/next nav
   - renders the roadmap + progress on the home page
   - adds a Copy button to every <pre class="cmd">
   - dark mode toggle and "mark as done" (saved in this browser only)

   It loads assets/js/modules.js itself, with a fresh URL on every
   visit. GitHub Pages lets browsers cache files for 10 minutes,
   which would otherwise hide a module for 10 minutes after merging.

   When you change THIS file, bump the ?v= number on its <script>
   tag in index.html, modules/_template.html and every module page.
   ========================================================= */
(function () {
  "use strict";

  var REPO = "https://github.com/kumar-purushottam/git-zero-to-pro";
  var KEY_DONE = "gzp-done";
  var KEY_THEME = "gzp-theme";
  var LEVELS = ["Beginner", "Intermediate", "Advanced", "Pro", "Reference"];

  var modules = [];
  var body = document.body;
  var root = body.getAttribute("data-root") || ".";
  var currentId = body.getAttribute("data-module");

  /* ---------- small helpers ---------- */
  function read(key) { try { return localStorage.getItem(key); } catch (e) { return null; } }
  function write(key, val) { try { localStorage.setItem(key, val); } catch (e) { /* storage blocked */ } }
  function getDone() {
    try { var v = JSON.parse(read(KEY_DONE) || "[]"); return Array.isArray(v) ? v : []; }
    catch (e) { return []; }
  }
  function isDone(id) { return getDone().indexOf(id) !== -1; }
  function toggleDone(id) {
    var list = getDone();
    var i = list.indexOf(id);
    if (i === -1) list.push(id); else list.splice(i, 1);
    write(KEY_DONE, JSON.stringify(list));
    return i === -1;
  }
  function moduleHref(m) { return root + "/modules/" + m.slug + ".html"; }
  function branchName(m) { return "module/" + m.slug; }
  function levelClass(level) { return "level-" + String(level).toLowerCase(); }
  function esc(s) {
    return String(s).replace(/[&<>"']/g, function (c) {
      return { "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&#39;" }[c];
    });
  }
  function ready(m) { return m.status === "ready"; }

  var BRANCH_ICON =
    '<svg viewBox="0 0 24 24" aria-hidden="true" fill="none" stroke-width="2.4" stroke-linecap="round">' +
    '<path d="M6 4v16" stroke="var(--main)"/>' +
    '<path d="M6 15c0-5 12-3 12-9" stroke="var(--branch)"/>' +
    '<circle cx="6" cy="19" r="2.4" fill="var(--surface)" stroke="var(--main)"/>' +
    '<circle cx="6" cy="5" r="2.4" fill="var(--surface)" stroke="var(--main)"/>' +
    '<circle cx="18" cy="6" r="2.4" fill="var(--surface)" stroke="var(--branch)"/></svg>';

  /* ---------- theme ---------- */
  function isDark() {
    var t = document.documentElement.getAttribute("data-theme");
    if (t) return t === "dark";
    return window.matchMedia && window.matchMedia("(prefers-color-scheme: dark)").matches;
  }
  function toggleTheme() {
    var next = isDark() ? "light" : "dark";
    document.documentElement.setAttribute("data-theme", next);
    write(KEY_THEME, next);
  }

  /* ---------- header ---------- */
  function renderHeader() {
    var h = document.getElementById("site-header");
    if (!h) return;
    h.innerHTML =
      '<div class="header-inner">' +
        (currentId ? '<button class="icon-btn menu-btn" id="menu-btn" aria-expanded="false" aria-controls="sidebar">Modules</button>' : "") +
        '<a class="brand" href="' + root + '/index.html">' + BRANCH_ICON + "Git Zero to Pro</a>" +
        '<nav class="header-links" aria-label="Site">' +
          '<a href="' + root + '/index.html#roadmap">Roadmap</a>' +
          '<a href="' + root + '/index.html#how">How it\'s built</a>' +
          '<a href="' + REPO + '" target="_blank" rel="noopener">GitHub repo</a>' +
        "</nav>" +
        '<button class="icon-btn" id="theme-btn" aria-label="Toggle dark mode" title="Toggle dark mode">◐</button>' +
      "</div>";

    document.getElementById("theme-btn").addEventListener("click", toggleTheme);
    var menu = document.getElementById("menu-btn");
    if (menu) {
      menu.addEventListener("click", function () {
        var layout = document.querySelector(".layout");
        var open = layout.classList.toggle("nav-open");
        menu.setAttribute("aria-expanded", String(open));
      });
    }
  }

  /* ---------- footer ---------- */
  function renderFooter() {
    var f = document.getElementById("site-footer");
    if (!f) return;
    f.innerHTML =
      "Built branch by branch. Every lesson arrived through a pull request · " +
      '<a href="' + REPO + '/pulls?q=is%3Apr" target="_blank" rel="noopener">See all pull requests</a>';
  }

  /* ---------- sidebar (module pages) ---------- */
  function renderSidebar() {
    var s = document.getElementById("sidebar");
    if (!s) return;
    var html = "";
    LEVELS.forEach(function (level) {
      var group = modules.filter(function (m) { return m.level === level; });
      if (!group.length) return;
      html += "<h4>" + esc(level) + "</h4><ol>";
      group.forEach(function (m) {
        var label = '<span class="num">' + esc(m.id) + "</span><span>" + esc(m.title) + "</span>";
        if (ready(m)) {
          var cur = m.id === currentId ? ' aria-current="page"' : "";
          var tick = isDone(m.id) ? '<span class="check" aria-label="done">✓</span>' : "";
          html += '<li><a href="' + moduleHref(m) + '"' + cur + ">" + label + tick + "</a></li>";
        } else {
          html += '<li><span class="soon" title="Being built on branch ' + esc(branchName(m)) + '">' + label + "</span></li>";
        }
      });
      html += "</ol>";
    });
    s.innerHTML = '<nav aria-label="Modules">' + html + "</nav>";
  }

  /* ---------- module header eyebrow ---------- */
  function renderEyebrow() {
    var e = document.querySelector(".eyebrow[data-auto]");
    var m = modules.filter(function (x) { return x.id === currentId; })[0];
    if (!e || !m) return;
    e.innerHTML =
      "<span>Module " + esc(m.id) + "</span>" +
      '<span class="badge ' + levelClass(m.level) + '">' + esc(m.level) + "</span>" +
      "<span>· " + esc(m.minutes) + " min</span>";
  }

  /* ---------- prev / done / next ---------- */
  function renderModuleNav() {
    var n = document.getElementById("module-nav");
    if (!n || !currentId) return;
    var readyList = modules.filter(ready);
    var idx = -1;
    readyList.forEach(function (m, i) { if (m.id === currentId) idx = i; });
    var prev = idx > 0 ? readyList[idx - 1] : null;
    var next = idx !== -1 && idx < readyList.length - 1 ? readyList[idx + 1] : null;

    function link(m, cls, dir) {
      if (!m) return '<span class="placeholder"></span>';
      return '<a class="' + cls + '" href="' + moduleHref(m) + '"><small>' + dir + "</small>" +
        esc(m.id) + " · " + esc(m.title) + "</a>";
    }
    var done = isDone(currentId);
    n.innerHTML =
      link(prev, "prev", "← Previous") +
      '<button class="btn done-btn" id="done-btn" aria-pressed="' + done + '">' +
        (done ? "✓ Done" : "Mark as done") + "</button>" +
      link(next, "next", "Next →");

    document.getElementById("done-btn").addEventListener("click", function () {
      var nowDone = toggleDone(currentId);
      this.setAttribute("aria-pressed", String(nowDone));
      this.textContent = nowDone ? "✓ Done" : "Mark as done";
      renderSidebar();
    });
  }

  /* ---------- home page: roadmap + progress ---------- */
  function renderRoadmap() {
    var r = document.getElementById("roadmap-list");
    if (!r) return;
    var html = "";
    LEVELS.forEach(function (level) {
      var group = modules.filter(function (m) { return m.level === level; });
      if (!group.length) return;
      html += '<div class="level-group"><h3><span class="badge ' + levelClass(level) + '">' + esc(level) + "</span></h3><div class=\"cards\">";
      group.forEach(function (m) {
        if (ready(m)) {
          var done = isDone(m.id);
          html +=
            '<a class="card" href="' + moduleHref(m) + '">' +
              '<span class="num">Module ' + esc(m.id) + "</span>" +
              "<h4>" + esc(m.title) + "</h4>" +
              '<span class="meta"><span>' + esc(m.minutes) + " min</span>" +
              (done ? '<span class="status status-done">✓ Done</span>' : '<span class="status status-ready">Merged into main</span>') +
              "</span></a>";
        } else {
          html +=
            '<div class="card soon">' +
              '<span class="num">Module ' + esc(m.id) + "</span>" +
              "<h4>" + esc(m.title) + "</h4>" +
              '<span class="meta"><span class="branch-name">' + esc(branchName(m)) + "</span>" +
              '<span class="status status-soon">Coming soon</span></span></div>';
        }
      });
      html += "</div></div>";
    });
    r.innerHTML = html;

    var p = document.getElementById("progress");
    if (p) {
      var merged = modules.filter(ready).length;
      var done = getDone().filter(function (id) {
        return modules.some(function (m) { return m.id === id && ready(m); });
      }).length;
      var pct = merged ? Math.round((done / merged) * 100) : 0;
      p.innerHTML =
        "<span><strong>" + merged + "</strong> of " + modules.length + " modules merged</span>" +
        '<span class="progress-bar" role="progressbar" aria-label="Modules you finished" aria-valuemin="0" aria-valuemax="100" aria-valuenow="' + pct + '"><span style="width:' + pct + '%"></span></span>' +
        "<span>you finished " + done + "</span>";
    }
  }

  /* ---------- copy buttons on <pre class="cmd"> ---------- */
  function addCopyButtons() {
    document.querySelectorAll("pre.cmd").forEach(function (pre) {
      var wrap = document.createElement("div");
      wrap.className = "code-wrap";
      pre.parentNode.insertBefore(wrap, pre);
      wrap.appendChild(pre);
      var btn = document.createElement("button");
      btn.className = "copy-btn";
      btn.type = "button";
      btn.textContent = "Copy";
      btn.addEventListener("click", function () {
        // Copy only commands: skip sample-output lines marked <span class="o">
        var clone = pre.cloneNode(true);
        clone.querySelectorAll(".o").forEach(function (o) { o.remove(); });
        var text = clone.textContent.replace(/\n{2,}/g, "\n").trim();
        var done = function () {
          btn.textContent = "Copied";
          btn.classList.add("copied");
          setTimeout(function () { btn.textContent = "Copy"; btn.classList.remove("copied"); }, 1500);
        };
        if (navigator.clipboard && navigator.clipboard.writeText) {
          navigator.clipboard.writeText(text).then(done, function () {});
        }
      });
      wrap.appendChild(btn);
    });
  }

  /* ---------- repo links: <a data-repo-link data-repo-path="/branches"> ---------- */
  function wireRepoLinks() {
    document.querySelectorAll("[data-repo-link]").forEach(function (a) {
      a.href = REPO + (a.getAttribute("data-repo-path") || "");
    });
  }

  function start() {
    modules = window.MODULES || [];
    renderHeader();
    renderFooter();
    renderSidebar();
    renderEyebrow();
    renderModuleNav();
    renderRoadmap();
    addCopyButtons();
    wireRepoLinks();
  }

  /* Load the module registry fresh (never from the browser cache). */
  var registry = document.createElement("script");
  registry.src = root + "/assets/js/modules.js?t=" + Date.now();
  registry.onload = start;
  registry.onerror = start;
  document.head.appendChild(registry);
})();
